<h2>Turn 1 Rules</h2>
<p>Winner of coin flip decides whether to go first – determined before game setup</p>
<p>Player going first does not draw a card at start of turn</p>
<p>Player going first cannot play supporters</p>
<p>Player going first can attack</p>
<p>Players may NOT play a stadium with same name as one currently in play</p>
<p>Stadium cards are considered trainers</p>
